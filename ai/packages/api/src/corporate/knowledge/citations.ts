/**
 * Якоря цитирования для `knowledge_search`.
 *
 * Формат общий с веб-поиском LibreChat: `turn{N}file{M}`, где символы
 * записаны литерально — обратной косой чертой и буквами, а не самим символом
 * U+E202. Клиент принимает обе записи (см. `STANDALONE_PATTERN` в
 * `client/src/utils/citations.ts`), но модели надёжнее выдают литеральную.
 *
 * Номер хода всегда нулевой, и это осознанно: в рантайме агентов номера хода
 * не существует (`runnableConfig.toolCall.turn` не проставляется никем), так
 * что развести по нему несколько вызовов инструмента внутри одного ответа
 * нельзя. Вместо этого разводим по второму числу — оно нумерует документ и
 * остаётся одним и тем же для документа на всём протяжении ответа, сколько бы
 * раз поиск ни вызывался.
 */

export const CITATION_TURN = 0;

/** Собирает якорь для документа с указанным номером. */
export function knowledgeAnchor(documentIndex: number): string {
  return `\\ue202turn${CITATION_TURN}file${documentIndex}`;
}

/**
 * Раздаёт документам стабильные номера для якорей в пределах одного ответа.
 *
 * Живёт столько же, сколько инструмент, то есть один пользовательский запрос:
 * модель вызывает поиск по три-четыре раза, выдачи пересекаются, и один и тот
 * же документ обязан получить один и тот же номер во всех вызовах — иначе
 * якорь из второго вызова указал бы на документ из первого.
 */
export class DocumentCitationIndex {
  private readonly byFileId: Map<string, number> = new Map();

  /** Номер документа: тот же при каждом следующем обращении. */
  public indexFor(fileId: string): number {
    const existing = this.byFileId.get(fileId);
    if (existing != null) {
      return existing;
    }
    const next = this.byFileId.size;
    this.byFileId.set(fileId, next);
    return next;
  }

  /** Сколько документов уже пронумеровано. */
  public get size(): number {
    return this.byFileId.size;
  }
}

/**
 * Правила цитирования, общие для обычного и обязательного режимов поиска.
 *
 * Отдельным блоком, а не строкой в описании инструмента: у веб-поиска это
 * сделано именно так (`buildWebSearchContext` в
 * `packages/api/src/tools/toolkits/web.ts`), и там модель якоря ставит, а у нас
 * при одной строке в конце описания — не ставила ни разу за двадцать шесть
 * ответов. Разница в том, что здесь инструкция попадает в системную часть
 * контекста и содержит примеры, которые можно скопировать буквально.
 */
const KNOWLEDGE_CITATION_RULES = `Отвечая по документам из базы знаний, ставь якорь источника сразу после факта, взятого из документа.

**Формат якоря — копируй последовательность буквально:** \\ue202turn0fileN

Здесь N — номер документа, он напечатан в поле «Якорь» карточки найденного фрагмента. Бери номер только оттуда, не придумывай и не перенумеровывай: у одного и того же документа номер не меняется, сколько бы раз ты ни вызывал поиск.

**Примеры (скопируй в точности):**
- Один источник: "Срок оспаривания — пять рабочих дней.\\ue202turn0file0"
- Два источника подряд: "Ключи меняются раз в девяносто дней.\\ue202turn0file1\\ue202turn0file2"

**Обязательно:**
- Выводи последовательность ровно так, как показано. Не заменяй её сносками, ссылками Markdown, значками [1], † или HTML.
- Ставь якорь после знака препинания, в конце предложения с фактом.
- На каждый документ, из которого ты что-то взял, поставь якорь хотя бы один раз.
- Если факт взят не из документов, а из твоих собственных знаний, якорь не ставь. Это важнее всего остального: по якорям сотруднику показывается список источников, и якорь у ненайденного в документах факта делает список ложным.

**Не повторяй один и тот же якорь подряд.** Когда несколько предложений или пунктов списка идут из одного документа, достаточно поставить его якорь один раз — в конце этого куска. Якорь отвечает на вопрос «из какого документа это взято», и если документ не менялся, повторять ответ незачем: сотруднику это только рвёт текст. Ставь якорь заново там, где меняется документ.`;

/** Системный блок с правилами цитирования для обычного режима: поиск доступен, модель решает сама, звать его или нет. */
export function buildKnowledgeSearchContext(): string {
  return `# \`knowledge_search\`: указание источников

${KNOWLEDGE_CITATION_RULES}`.trim();
}

/**
 * Системный блок для режима обязательного поиска (переключатель «искать в
 * документах» включён). Добавляет к тем же правилам цитирования требование
 * вызвать поиск перед ответом и запрет тихо подменять пустой результат
 * общими знаниями модели — без этого запрета модель в такой ситуации
 * плавно съезжает на общие сведения, и сотрудник не понимает, что ответ не
 * из документов компании.
 */
export function buildKnowledgeSearchRequiredContext(): string {
  return `# \`knowledge_search\`: обязательный поиск и указание источников

Прежде чем отвечать на вопрос пользователя, обязательно вызови \`knowledge_search\`. Отвечай только тем, что нашлось в документах.

Если поиск не нашёл по вопросу ничего подходящего, прямо скажи, что в документах компании этой информации нет, и не продолжай ответ по своим общим знаниям. Это требование важнее всего остального: сотрудник должен точно знать, взят ответ из документов компании или нет.

${KNOWLEDGE_CITATION_RULES}`.trim();
}
